-- Comments on species. Run in the Supabase SQL editor after setup.sql.
-- Matches the generated types in lib/schema.ts (regenerate with `npm run types` after changes).

create table comments (
  id int generated by default as identity primary key,
  species_id int not null references species on delete cascade,
  author uuid not null references profiles on delete cascade,
  content text not null,
  created_at timestamp with time zone not null default now()
);

alter table comments
  enable row level security;

create policy "Comments are viewable by everyone." on comments
  for select using (true);

create policy "Users can insert their own comments." on comments
  for insert with check (auth.uid() = author);

create policy "Users can delete their own comments." on comments
  for delete using (auth.uid() = author);
